#!/usr/bin/env bash
# ==============================================================================
# apply_keycloak_wxo_config.sh
# Automates Keycloak & MCP server configuration for watsonx Orchestrate.
# ==============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd -- "${SCRIPT_DIR}/../.." && pwd)"
INFRA_DIR="${REPO_ROOT}/infrastructure/galaxium-travels-infrastructure-tsuedbro"
OAUTH_DIR="${INFRA_DIR}/local-container/booking_system_mcp_oauth2_no_implicit_flow"

echo "=== watsonx Orchestrate Keycloak Configuration Helper ==="

# 1. Detect Host LAN IP
if [[ -z "${LOCAL_NET_IP:-}" ]]; then
  if [[ "$(uname)" == "Darwin" ]]; then
    LOCAL_NET_IP="$(ipconfig getifaddr en0 2>/dev/null || ipconfig getifaddr en1 2>/dev/null || true)"
  else
    LOCAL_NET_IP="$(hostname -I 2>/dev/null | awk '{print $1}' || true)"
  fi
fi

if [[ -z "${LOCAL_NET_IP:-}" ]]; then
  echo "[ERROR] Could not automatically detect host LAN IP."
  echo "Please export LOCAL_NET_IP=<your-ip> and rerun this script."
  exit 1
fi

echo "[INFO] Using Host LAN IP: ${LOCAL_NET_IP}"

# 2. Check Infrastructure Repository
if [[ ! -d "${INFRA_DIR}" ]]; then
  echo "[INFO] Cloning Galaxium infrastructure repository..."
  mkdir -p "${REPO_ROOT}/infrastructure"
  git clone https://github.com/thomassuedbroecker/galaxium-travels-infrastructure-tsuedbro.git "${INFRA_DIR}"
  (cd "${INFRA_DIR}" && git checkout v6.1.1)
fi

# 3. Create mcp.env configured for watsonx Orchestrate
REALM_DIR="${SCRIPT_DIR}/realm"

echo "[INFO] Writing configuration to ${OAUTH_DIR}/mcp.env..."
cat <<EOF > "${OAUTH_DIR}/mcp.env"
# Auto-generated by apply_keycloak_wxo_config.sh for watsonx Orchestrate integration

export MCP_HOST_PORT=8084
export KEYCLOAK_HOST_PORT=8086

# Public URLs bound to host LAN IP so watsonx Orchestrate Lima VM can reach them:
export KEYCLOAK_PUBLIC_BASE_URL="http://${LOCAL_NET_IP}:8086"
export MCP_PUBLIC_BASE_URL="http://${LOCAL_NET_IP}:8084"

# Custom realm directory with watsonx Orchestrate client configurations:
export KEYCLOAK_REALM_DIR="${REALM_DIR}"

# Client credentials for watsonx Orchestrate connection:
export OIDC_CLIENT_ID="web-app-proxy"
export OIDC_CLIENT_SECRET="web-app-proxy-secret"
EOF

echo "[SUCCESS] Configuration applied to ${OAUTH_DIR}/mcp.env"
echo ""
echo "Next steps:"
echo "1. Start/restart the OAuth2 stack:"
echo "   cd ${INFRA_DIR}"
echo "   docker compose -f local-container/booking_system_mcp_oauth2_no_implicit_flow/docker_compose.yaml down --remove-orphans"
echo "   bash local-container/booking_system_mcp_oauth2_no_implicit_flow/start.sh"
echo "   bash local-container/booking_system_mcp_oauth2_no_implicit_flow/verify.sh"
echo ""
echo "2. Register the MCP server in watsonx Orchestrate:"
echo "   cd ${REPO_ROOT}/watsonx-orchestrate-adk"
echo "   bash wxo_add_oauth2_mcp_server.sh"
